# is / is not vs == / !=
######################################################################################
x = ["apple", "banana"]
y = ["apple", "banana"]
z = x

# 1. 값(Value) 비교: ==, !=
print(x == y)      # True  (내용물이 같음)
print(x != y)      # False

# 2. 주소(Identity) 비교: is, is not
print(x is y)      # False (내용은 같지만 서로 다른 메모리에 독립 생성됨)
print(x is not y)  # True  (주소가 다르므로 True)

print(x is z)      # True  (z는 x와 같은 메모리 주소를 가리킴)



