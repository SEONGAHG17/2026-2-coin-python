# 비트 연산자
"""
& (비트 AND): 두 비트가 모두 1일 때만 1을 반환합니다.
| (비트 OR): 두 비트 중 하나라도 1이면 1을 반환합니다.
^ (비트 XOR): 두 비트가 서로 다를 때만 1을 반환합니다. (같으면 0)
~ (비트 NOT / 보수): 비트를 반전시킵니다. (1은 0으로, 0은 1로)
<< (왼쪽 시프트): 비트를 지정한 횟수만큼 왼쪽으로 이동시킵니다. (오른쪽에 0이 채워짐)
>> (오른쪽 시프트): 비트를 지정한 횟수만큼 오른쪽으로 이동시킵니다.
"""

a = 5  # 이진수: 0101
b = 3  # 이진수: 0011

# 1. & (AND) : 둘 다 1이어야 1
# 0101 & 0011 = 0001 (십진수 1)
print(a & b)  # 1

# 2. | (OR) : 하나라도 1이면 1
# 0101 | 0011 = 0111 (십진수 7)
print(a | b)  # 7

# 3. ^ (XOR) : 서로 다르면 1
# 0101 ^ 0011 = 0110 (십진수 6)
print(a ^ b)  # 6

# 4. ~ (NOT) : 비트 반전 (공식: -(x + 1))
# ~5 = -(5 + 1) = -6
print(~a)     # -6

# 5. << (왼쪽 시프트) : 비트를 왼쪽으로 2칸 밀기
# 0101 -> 010100 (십진수 20)
# 팁: 왼쪽으로 1칸 밀 때마다 숫자가 2배씩 커집니다 (5 * 2 * 2 = 20)
print(a << 2) # 20

# 6. >> (오른쪽 시프트) : 비트를 오른쪽으로 1칸 밀기
# 0101 -> 0010 (십진수 2)
# 팁: 오른쪽으로 1칸 밀 때마다 숫자가 2로 나눈 몫이 됩니다 (5 // 2 = 2)
print(a >> 1) # 2
