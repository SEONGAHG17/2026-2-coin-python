######################################################################################
# is / is not 연산자 : 메모리 상의 실제 객체 주소(Identity)가 같은지 비교
######################################################################################
list_a = [1, 2, 3]
list_b = [1, 2, 3]
list_c = list_a


# --- 메모리 주소 확인 ---
print(id(list_a))  # 예: 140234567812032
print(id(list_b))  # 예: 140234567812160 (list_a와 다름!)
print(id(list_c))  # 예: 140234567812032 (list_a와 동일!)

# --- is 연산자 ---
print(list_a is list_b)  # False (주소가 서로 다름)
print(list_a is list_c)  # True  (완전히 같은 메모리 주소를 가리킴)

# --- is not 연산자 ---
print(list_a is not list_b)  # True  (주소가 다르므로 True)
print(list_a is not list_c)  # False (주소가 같으므로 False)


