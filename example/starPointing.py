# ==================== 별찍기 답안 ====================

# Python 반복문 문제 - 별찍기 답안


# 문제 1. 좌측 삼각형
n = 5

for i in range(1, n + 1):
    print("*" * i)


# 문제 2. 역좌측 삼각형
n = 5

for i in range(n, 0, -1):
    print("*" * i)


# 문제 3. 우측 삼각형
n = 5

for i in range(1, n + 1):
    print(" " * (n - i) + "*" * i)


# 문제 4. 역우측 삼각형
n = 5

for i in range(n, 0, -1):
    print(" " * (n - i) + "*" * i)


# 문제 5. 피라미드
n = 5

for i in range(1, n + 1):
    space = n - i
    star = 2 * i - 1

    print(" " * space + "*" * star)


# 문제 6. 역피라미드
n = 5

for i in range(n, 0, -1):
    space = n - i
    star = 2 * i - 1

    print(" " * space + "*" * star)


# 문제 7. 숫자 피라미드
n = 5

for i in range(1, n + 1):
    space = n - i
    number = 2 * i - 1

    print(" " * space + str(i) * number)


# 문제 8. 다이아몬드
n = 5

for i in range(1, n + 1):
    space = n - i
    star = 2 * i - 1

    print(" " * space + "*" * star)

for i in range(n - 1, 0, -1):
    space = n - i
    star = 2 * i - 1

    print(" " * space + "*" * star)


# 문제 9. 빈 피라미드
n = 5

for i in range(1, n + 1):
    space = n - i

    if i == 1:
        print(" " * space + "*")
    elif i == n:
        print("*" * (2 * i - 1))
    else:
        inside_space = 2 * i - 3
        print(" " * space + "*" + " " * inside_space + "*")


# 문제 10. 별찍기 종합
n = 7

for i in range(1, n + 1):
    space = n - i
    star = 2 * i - 1

    print(" " * space + "*" * star)
