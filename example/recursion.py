# ------------------------------------------------------------------------------
# 문제 12. 리스트의 최댓값 찾기 (max 함수 쓰지 않기)
# [설명] 비어있지 않은 숫자 리스트 nums에서 가장 큰 값을 찾으세요.
# 예: find_max([3, 7, 2, 9, 5]) -> 9
# ------------------------------------------------------------------------------
# [답안]
def find_max(nums: list) -> int:
    if len(nums) == 1:
        return nums[0]
    sub_max = find_max(nums[1:])
    return nums[0] if nums[0] > sub_max else sub_max

# [해설]
# 리스트가 1개 남을 때까지 쪼갠 뒤, 뒤에서부터 올라오며 두 값 중 더 큰 값을 선택합니다.


# ------------------------------------------------------------------------------
# 문제 13. 리스트 뒤집기 (reverse/슬라이싱::-1 금지)
# [설명] 리스트 nums의 순서를 반대로 뒤집은 새 리스트를 반환하세요.
# 예: reverse_list([1, 2, 3]) -> [3, 2, 1]
# ------------------------------------------------------------------------------
# [답안]
def reverse_list(nums: list) -> list:
    if len(nums) <= 1:
        return nums
    return [nums[-1]] + reverse_list(nums[:-1])

# [해설]
# 맨 마지막 원소([nums[-1]])를 맨 앞으로 빼고, 앞쪽 나머지(nums[:-1])를 뒤집어 붙입니다.


# ------------------------------------------------------------------------------
# 문제 14. 리스트에서 특정 값 전부 제거하기
# [설명] 리스트 nums에서 target과 일치하는 모든 값을 삭제한 새 리스트를 반환하세요.
# 예: remove_value([1, 2, 3, 2, 4], 2) -> [1, 3, 4]
# ------------------------------------------------------------------------------
# [답안]
def remove_value(nums: list, target: int) -> list:
    if not nums:
        return []
    rest = remove_value(nums[1:], target)
    if nums[0] == target:
        return rest
    else:
        return [nums[0]] + rest

# [해설]
# 첫 원소가 target과 같으면 버리고, 다를 때만 결과 리스트에 포함시킵니다.


# ------------------------------------------------------------------------------
# 문제 15. 리스트가 오름차순으로 정렬되어 있는지 검사
# [설명] 리스트 nums가 오름차순(점점 커지거나 같은 순서)이면 True, 아니면 False를 반환하세요.
# 예: is_sorted([1, 3, 5, 5, 8]) -> True, is_sorted([1, 4, 2]) -> False
# ------------------------------------------------------------------------------
# [답안]
def is_sorted(nums: list) -> bool:
    if len(nums) <= 1:
        return True
    if nums[0] > nums[1]:
        return False
    return is_sorted(nums[1:])

# [해설]
# 바로 옆 원소(nums[0]와 nums[1])를 비교하여 앞이 더 크면 즉시 탈락(False)입니다.



