# ------------------------------------------------------------------------------
# 문제 1. 1부터 N까지의 곱 (팩토리얼)
# [설명] 정수 n(n >= 1)을 받아 1부터 n까지의 곱을 구하세요.
# 예: factorial(4) -> 4 * 3 * 2 * 1 = 24
# ------------------------------------------------------------------------------
# [답안]
def factorial(n: int) -> int:
    if n <= 1:
        return 1
    return n * factorial(n - 1)

# [해설]
# 탈출 조건: n이 1 이하이면 더 이상 곱할 필요가 없으므로 1을 반환합니다.
# 점화식: n! = n * (n - 1)!


# ------------------------------------------------------------------------------
# 문제 2. 거듭제곱 계산기 (a의 b제곱)
# [설명] 두 정수 a, b(b >= 0)를 받아 a의 b제곱(a^b)을 구하세요.
# 예: power(2, 3) -> 2 * 2 * 2 = 8, power(5, 0) -> 1
# ------------------------------------------------------------------------------
# [답안]
def power(a: int, b: int) -> int:
    if b == 0:
        return 1
    return a * power(a, b - 1)

# [해설]
# 탈출 조건: 어떤 수의 0제곱은 항상 1입니다.
# 점화식: a^b = a * a^(b-1)


# ------------------------------------------------------------------------------
# 문제 3. 1부터 N까지의 짝수 합 구하기
# [설명] 양의 정수 n이 주어졌을 때, 1부터 n 이하의 모든 "짝수"들의 합만 구하세요.
# 예: sum_evens(6) -> 6 + 4 + 2 = 12, sum_evens(5) -> 4 + 2 = 6
# ------------------------------------------------------------------------------
# [답안]
def sum_evens(n: int) -> int:
    if n <= 1:
        return 0
    if n % 2 == 0:
        return n + sum_evens(n - 2)
    else:
        return sum_evens(n - 1)

# [해설]
# n이 짝수면 n을 더하고 2 작은 짝수로 넘어가며, 홀수면 n을 버리고 n-1로 넘깁니다.


# ------------------------------------------------------------------------------
# 문제 4. N번 반복 출력 리스트 만들기
# [설명] 문자열 text와 횟수 n을 받아, text가 n개 들어있는 리스트를 만드세요.
# 예: repeat_text("안녕", 3) -> ["안녕", "안녕", "안녕"]
# ------------------------------------------------------------------------------
# [답안]
def repeat_text(text: str, n: int) -> list:
    if n <= 0:
        return []
    return [text] + repeat_text(text, n - 1)

# [해설]
# 탈출 조건: n이 0이면 빈 리스트([])를 반환합니다.
# 리스트 덧셈 연산자(+)를 활용해 요소를 하나씩 붙여나갑니다.


# ------------------------------------------------------------------------------
# 문제 5. 카운트다운 문자열 만들기
# [설명] 숫자 n부터 1까지 쉼표로 연결된 문자열을 만드세요.
# 예: countdown_str(4) -> "4,3,2,1"
# ------------------------------------------------------------------------------
# [답안]
def countdown_str(n: int) -> str:
    if n <= 1:
        return "1"
    return str(n) + "," + countdown_str(n - 1)

# [해설]
# 탈출 조건인 n=1일 때 "1"만 반환하고, 그 전까지는 "n," 형태로 이어붙입니다.



