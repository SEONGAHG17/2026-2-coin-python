# 문제 20. 하노이의 탑 이동 횟수 계산
# [설명] n개의 원판을 다른 기둥으로 모두 옮기는 최소 이동 횟수를 구하세요.
# 공식: 1개일 때는 1번, n개일 때는 [n-1개를 옮기는 횟수] * 2 + 1 번입니다.
# 예: hanoi_count(3) -> 7, hanoi_count(4) -> 15
# ------------------------------------------------------------------------------
# [답안]
def hanoi_count(n: int) -> int:
    if n <= 1:
        return 1
    return 2 * hanoi_count(n - 1) + 1

# [해설]
# 맨 아래 원판을 옮기기 위해 위의 n-1개를 치우고, 마지막 원판을 옮긴 뒤 다시 n-1개를 올립니다.



