# 문제 6. 문자열 길이 구하기 (len 함수 쓰지 않기)
# [설명] 문자열 s의 길이를 내장 함수 len()을 쓰지 않고 재귀로 구하세요.
# 예: recursive_len("python") -> 6, recursive_len("") -> 0
# ------------------------------------------------------------------------------
# [답안]
def recursive_len(s: str) -> int:
    if s == "":
        return 0
    return 1 + recursive_len(s[1:])

# [해설]
# 문자열의 첫 글자를 떼어내며 1을 더하고, 나머지 뒷부분(s[1:])으로 재귀를 호출합니다.


# ------------------------------------------------------------------------------
# 문제 7. 특정 문자 등장 횟수 세기
# [설명] 문자열 s 안에 특정 문자 target이 몇 번 나오는지 세어 반환하세요.
# 예: count_char("banana", "a") -> 3
# ------------------------------------------------------------------------------
# [답안]
def count_char(s: str, target: str) -> int:
    if s == "":
        return 0
    match = 1 if s[0] == target else 0
    return match + count_char(s[1:], target)

# [해설]
# 첫 글자가 target과 같은지 검사(1 또는 0)한 뒤 나머지 글자(s[1:])의 결과를 누적합니다.


# ------------------------------------------------------------------------------
# 문제 8. 회문(팰린드롬) 판별기
# [설명] 앞에서 읽으나 뒤에서 읽으나 똑같은 단어를 회문이라고 합니다.
# 주어진 문자열 s가 회문이면 True, 아니면 False를 반환하세요.
# 예: is_palindrome("level") -> True, is_palindrome("robot") -> False
# ------------------------------------------------------------------------------
# [답안]
def is_palindrome(s: str) -> bool:
    if len(s) <= 1:
        return True
    if s[0] != s[-1]:
        return False
    return is_palindrome(s[1:-1])

# [해설]
# 양 끝 글자(s[0], s[-1])가 다르면 즉시 False이고, 같으면 양 끝을 깎아낸 s[1:-1]을 검사합니다.


# ------------------------------------------------------------------------------
# 문제 9. 십진수를 이진수 문자열로 변환하기
# [설명] 양의 정수 n을 2진수 형태의 문자열로 변환하세요.
# 예: to_binary(10) -> "1010", to_binary(7) -> "111"
# ------------------------------------------------------------------------------
# [답안]
def to_binary(n: int) -> str:
    if n <= 1:
        return str(n)
    return to_binary(n // 2) + str(n % 2)

# [해설]
# 2로 나눈 몫(n // 2)을 계속 앞으로 보내고, 나머지(n % 2)를 맨 뒤에 붙이는 2진법 변환 원리입니다.


# ------------------------------------------------------------------------------
# 문제 10. 최대공약수(GCD) 구하기 (유클리드 호제법)
# [설명] 두 정수 a, b의 최대공약수를 구하세요.
# 유클리드 공식: gcd(a, b) = gcd(b, a % b)이며, b가 0이 되면 그때의 a가 답입니다.
# 예: gcd(48, 18) -> 6
# ------------------------------------------------------------------------------
# [답안]
def gcd(a: int, b: int) -> int:
    if b == 0:
        return a
    return gcd(b, a % b)

# [해설]
# 수학의 대표적인 재귀 알고리즘인 유클리드 호제법 공식 그대로 작성합니다.



