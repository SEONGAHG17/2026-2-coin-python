# 문제 16. 피보나치 수열 N번째 값 구하기
# [설명] 피보나치 수열은 앞의 두 숫자를 더해 다음 숫자를 만듭니다.
# F(0)=0, F(1)=1 일 때 N번째 피보나치 수를 구하세요.
# 예: fib(5) -> 5 (수열: 0, 1, 1, 2, 3, 5, 8...)
# ------------------------------------------------------------------------------
# [답안]
def fib(n: int) -> int:
    if n <= 0:
        return 0
    if n == 1:
        return 1
    return fib(n - 1) + fib(n - 2)

# [해설]
# 2개의 자기 자신을 동시에 부르는 전형적인 다중 분기 재귀 구조입니다.


