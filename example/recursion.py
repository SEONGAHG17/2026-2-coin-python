# 문제 18. 이진 탐색(Binary Search) 재귀 구현
# [설명] 이미 정렬된 리스트 arr와 목표값 target이 주어졌을 때,
# 중간값과 비교하여 절반씩 범위를 줄여나가면서 target이 들어있으면 True, 없으면 False를 반환하세요.
# 예: binary_search([1, 3, 5, 7, 9, 11], 7) -> True
# ------------------------------------------------------------------------------
# [답안]
def binary_search(arr: list, target: int) -> bool:
    if not arr:
        return False
    mid = len(arr) // 2
    if arr[mid] == target:
        return True
    elif arr[mid] > target:
        return binary_search(arr[:mid], target)
    else:
        return binary_search(arr[mid + 1:], target)

# [해설]
# 가운데 값(mid)을 기준으로 왼쪽 절반 또는 오른쪽 절반 중 한 쪽만 택해 범위를 반으로 좁힙니다.


# ------------------------------------------------------------------------------
# 문제 19. 중첩 딕셔너리(트리)의 모든 단말 값(Leaf) 합산
# [설명] 회사 조직도처럼 딕셔너리 안에 딕셔너리가 들어있는 트리 구조가 있습니다.
# 숫자 값들만 전부 찾아서 합산하세요.
# 예: data = {"A": 10, "B": {"C": 20, "D": {"E": 30}}} -> 60
# ------------------------------------------------------------------------------
# [답안]
def sum_nested_dict(d: dict) -> int:
    total = 0
    for key in d:
        val = d[key]
        if isinstance(val, dict):
            total += sum_nested_dict(val)
        elif isinstance(val, int):
            total += val
    return total

# [해설]
# 값이 또 딕셔너리면 하위 부서로 재귀 호출을 들어가고, 숫자면 합계에 더합니다.


