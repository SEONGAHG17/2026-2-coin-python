# 2. 재귀함수를 만들 때 반드시 필요한 2가지 (★가장 중요★)
# ==============================================================================
# 1) 탈출 조건 (Base Case, 기저 조건):
#    "언제 멈출 것인가?"를 정하는 if문입니다.
#    이 조건이 없으면 함수가 끝나지 않고 영원히 자기 자신을 호출하다가 컴퓨터가 뻗습니다.
#
# 2) 자기 호출 (Recursive Step):
#    "문제를 더 작은 단위로 줄여서 자기 자신을 부르는 단계"입니다.
#    호출할 때마다 탈출 조건에 점점 가까워져야 합니다. (예: n - 1)


# ==============================================================================
# 예제 1. 카운트다운 (함수가 파고들어가는 순서 눈으로 확인하기)
# ==============================================================================
print("=" * 60)
print("[예제 1] 카운트다운 실행")
print("=" * 60)

def countdown(n):
    # [1] 탈출 조건: n이 0이 되면 멈추고 함수 종료!
    if n == 0:
        print(" 발사!! (탈출 조건 도달)")
        return

    # [2] 작업 수행 및 자기 호출
    print(f"카운트: {n}")
    countdown(n - 1)  # 숫자를 1 줄여서 다시 자신을 부름

countdown(3)
# 실행 순서:
# countdown(3) -> 3 출력 -> countdown(2) 호출
# countdown(2) -> 2 출력 -> countdown(1) 호출
# countdown(1) -> 1 출력 -> countdown(0) 호출
# countdown(0) -> "발사!!" 출력 후 종료!
print()


# ==============================================================================
# 예제 2. 팩토리얼 계산하기 (되돌아오면서 결과 합치기)
# ==============================================================================
# 팩토리얼(!)이란?
# 3! = 3 * 2 * 1
# 5! = 5 * 4 * 3 * 2 * 1
#
# 규칙(점화식):
# 5! = 5 * (4!)
# n! = n * (n - 1)!
# 1! = 1 (더 이상 쪼갤 수 없는 끝)
# ==============================================================================
print("=" * 60)
print("[예제 2] 팩토리얼 계산 과정 눈으로 보기")
print("=" * 60)

def factorial(n):
    # [1] 탈출 조건: 1 이하가 되면 1을 돌려줌
    if n <= 1:
        print(f"  -> n={n}에 도달! 이제 돌아가면서 계산을 시작합니다.")
        return 1

    # [2] 자기 호출
    print(f"  factorial({n}) 호출됨: {n} * factorial({n - 1}) 계산 대기 중...")
    result = n * factorial(n - 1)
    print(f"  <- factorial({n}) 완료: 결과값 {result}")
    return result

print(f"최종 4! 결과: {factorial(4)}\n")


