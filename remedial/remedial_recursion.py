# 예제 3. 1부터 N까지의 합 구하기
# ==============================================================================
# 1부터 5까지의 합 = 5 + (1부터 4까지의 합)
# sum_to_n(n) = n + sum_to_n(n - 1)
# ==============================================================================
print("=" * 60)
print("[예제 3] 1부터 N까지의 자연수 총합")
print("=" * 60)

def sum_to_n(n):
    # 탈출 조건: n이 1이면 그냥 1 반환
    if n <= 1:
        return 1
    
    # 자기 호출: 현재 n + (n-1까지의 합)
    return n + sum_to_n(n - 1)

print(f"1부터 10까지의 합: {sum_to_n(10)}\n")


