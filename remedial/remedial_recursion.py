# 재귀함수(Recursive Function)란?
# -> "함수 내부에서 '자기 자신(자기 이름)'을 다시 호출하는 함수"를 말합니다.
#
# 러시아 인형 '마트료시카'를 열면 그 안에 똑같이 생긴 더 작은 인형이 계속 나오고,
# 거울 앞에 거울을 대면 거울 속에 거울이 끝없이 비치는 것과 같은 원리입니다.


