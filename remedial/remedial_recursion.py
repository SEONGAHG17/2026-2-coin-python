def reverse_text(text):
    # 탈출 조건: 글자가 없거나 1글자면 그대로 반환
    if len(text) <= 1:
        return text

    # 맨 뒷글자 + 나머지 글자들을 뒤집은 결과
    return text[-1] + reverse_text(text[:-1])

original = "python"
print(f"원래 단어: {original}")
print(f"뒤집은 결과: {reverse_text(original)}\n")


