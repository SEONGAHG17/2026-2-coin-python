# .sort() vs sorted()


"""
가변 자료형의 특지에서 결정적인 차이 발생!
결론이 뭐냐?
	- .sort() : 가변 자료형의 트징을활용해 원본을 직접 수정한다
    - sotted() : 불변/가변 상관없이 항상 새로운 갹채를 생성한다
"""

"""
기능				.sort()	리스트 메서드			sorted() 내장 함수
-----------------------------------------------------------------------------

동작 방식 			원본 객체를 직접 정렬한다 			원본은 두고 새로 정렬된 리스트를 생성한다

반환 값 			None						정렬된 새 리스트 객체

대상 자료형 		list 						ilst, tuple, dict, str 등 모든 반복 가능 객체

메모리 주소. 		정렬 후에도 기본 메모리 주소 유지 	원본과 완전히 다른 새 메모리 주소 할당 
"""

# 리스트의 메서드 
"""
리스트는 가변 자료형이기에 새 리스트를 만들지 않고도 내부 요소의 순서 변경 가능
"""
a = [3, 1, 2]
print("정렬 전 주소:", id(a))

# 원본 리스트를 직접 정렬 (반환값은 None)
result = a.sort() 

print("정렬 후 원본:", a)       # [1, 2, 3] (원본이 바뀜)
print("반환된 결과:", result)  # None
print("정렬 후 주소:", id(a))   # 주소값이 정렬 전과 '동일' (가변 객체의 특징)


# 내장함수
"""
우ㅓㄴ본 자료형이 무엇이든(가변/불변) 우ㅓㄴ본을 안전하게 보호하기 위해
무조건 정렬된 새로운 리스트를 복사 해 만든다
"""
a = [3, 1, 2]
print("정렬 전 주소:", id(a))

# 원본 리스트를 직접 정렬 (반환값은 None)
result = a.sort() 

print("정렬 후 원본:", a)       # [1, 2, 3] (원본이 바뀜)
print("반환된 결과:", result)  # None
print("정렬 후 주소:", id(a))   # 주소값이 정렬 전과 '동일' (가변 객체의 특징)



